import jwt from "jsonwebtoken";
import { describe, expect, it } from "vitest";
import { comparePassword, hashPassword } from "../src/modules/auth/password.js";
import { JwtService, formatRfc3339, hashRefreshToken, newRefreshToken } from "../src/modules/auth/tokens.js";

const SECRET = "test-secret-key-at-least-32-chars!!";

describe("refresh tokens", () => {
  it("hash is deterministic", () => {
    expect(hashRefreshToken("abc")).toBe(hashRefreshToken("abc"));
    expect(hashRefreshToken("abc")).toMatch(/^[0-9a-f]{64}$/);
  });

  it("tokens are unique and match their hash", () => {
    const a = newRefreshToken();
    const b = newRefreshToken();
    expect(a.raw).not.toBe(b.raw);
    expect(a.hash).not.toBe(b.hash);
    expect(hashRefreshToken(a.raw)).toBe(a.hash);
    expect(a.raw).toMatch(/^[A-Za-z0-9_-]{43}$/);
  });
});

describe("JwtService", () => {
  const svc = new JwtService(SECRET);

  it("round-trips the Go claim names", () => {
    const { token, expiresAt } = svc.issueAccessToken("uid-1", "a@b.com", "super_admin");
    const claims = svc.parseAccessToken(token);
    expect(claims).toMatchObject({ uid: "uid-1", email: "a@b.com", role: "super_admin", sub: "uid-1", iss: "crm-api" });
    expect(claims.exp * 1000).toBe(expiresAt.getTime());
  });

  it("rejects other secrets, other algorithms and expired tokens", () => {
    const other = new JwtService("another-secret-another-secret!!!!").issueAccessToken("u", "e", "r").token;
    expect(() => svc.parseAccessToken(other)).toThrow();

    const hs512 = jwt.sign({ uid: "u" }, SECRET, { algorithm: "HS512" });
    expect(() => svc.parseAccessToken(hs512)).toThrow();

    const expired = jwt.sign({ uid: "u", exp: Math.floor(Date.now() / 1000) - 10 }, SECRET, { algorithm: "HS256" });
    expect(() => svc.parseAccessToken(expired)).toThrow();
  });

  it("accepts a token signed the way the Go backend signs it", () => {
    const now = Math.floor(Date.now() / 1000);
    const goToken = jwt.sign(
      { uid: "u-go", email: "go@b.com", role: "sales_executive", iss: "crm-api", sub: "u-go", exp: now + 900, iat: now },
      SECRET,
      { algorithm: "HS256", noTimestamp: true },
    );
    expect(svc.parseAccessToken(goToken).uid).toBe("u-go");
  });
});

describe("passwords", () => {
  it("hash and compare", async () => {
    const hash = await hashPassword("ChangeMe123!");
    expect(await comparePassword(hash, "ChangeMe123!")).toBe(true);
    expect(await comparePassword(hash, "wrong")).toBe(false);
  });

  it("verifies a Go bcrypt ($2a$, cost 12) hash", async () => {
    // Generated by golang.org/x/crypto/bcrypt for "ChangeMe123!".
    const goHash = "$2a$12$u5AoeO6wVwYFbxnuB4cHz.DAnbXt9LllY633z6hKG9NDg4kVsoLue";
    expect(await comparePassword(goHash, "ChangeMe123!")).toBe(true);
    expect(await comparePassword(goHash, "ChangeMe123")).toBe(false);
  });
});

describe("formatRfc3339", () => {
  it("drops milliseconds like Go's RFC3339 layout", () => {
    expect(formatRfc3339(new Date("2026-09-30T07:25:19.492Z"))).toBe("2026-09-30T07:25:19Z");
  });
});
